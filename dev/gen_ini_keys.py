"""Regenerate src/misterfpga_mcp/ini_keys.py from a Main_MiSTer checkout.

    python dev/gen_ini_keys.py ../Main_MiSTer > src/misterfpga_mcp/ini_keys.py

Reads `ini_vars[]` in Main_MiSTer's cfg.cpp: every key MiSTer.ini understands,
with its type and numeric range. Only those facts are copied (names, types,
bounds); Main_MiSTer is GPL-3.0 and none of its code is. String lengths come
from `sizeof(cfg.x)`, which this can't evaluate, so strings get a fixed cap in
ini.py instead.
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ENTRY = re.compile(r'\{\s*"([A-Z0-9_]+)",\s*\(void\s*\*\)\s*.+?,\s*([A-Z0-9]+),\s*([^,]+?),\s*(.+?)\s*\},?\s*$')


def number(text: str) -> int | float | None:
    text = text.strip()
    try:
        return int(text, 0)
    except ValueError:
        pass
    try:
        return float(text)
    except ValueError:
        return None  # sizeof(...) and friends


def main(checkout: Path) -> None:
    src = (checkout / "cfg.cpp").read_text()
    body = src[src.index("ini_vars[] =") : src.index("};", src.index("ini_vars[] ="))]
    sha = subprocess.run(["git", "-C", str(checkout), "rev-parse", "--short", "HEAD"], capture_output=True, text=True)
    rows = []
    for line in body.splitlines():
        m = ENTRY.match(line.strip())
        if m:
            name, kind, lo, hi = m.groups()
            rows.append((name, kind, number(lo), number(hi)))
    print('"""MiSTer.ini keys: generated by dev/gen_ini_keys.py from Main_MiSTer cfg.cpp `ini_vars[]`.')
    print()
    print(f"Main_MiSTer commit {sha.stdout.strip() or '?'}. (name, type, min, max); None where cfg.cpp uses sizeof().")
    print("Facts only (names, types, bounds): Main_MiSTer is GPL-3.0 and none of its code is copied.")
    print("ASSUMPTION M-INI-KEYS")
    print('"""')
    print()
    print("from __future__ import annotations")
    print()
    print("INI_VARS: tuple[tuple[str, str, int | float | None, int | float | None], ...] = (")
    for row in rows:
        print(f"    {row!r},")
    print(")")


if __name__ == "__main__":
    main(Path(sys.argv[1]))
